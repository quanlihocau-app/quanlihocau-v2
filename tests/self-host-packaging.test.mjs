import assert from "node:assert/strict";
import fs from "node:fs";
import test from "node:test";

test("Dockerfile standalone, non-root, có sharp và entrypoint chỉ migrate deploy", () => {
    const docker = fs.readFileSync("Dockerfile", "utf8");
    assert.match(docker, /FROM node:24-bookworm-slim AS runner/);
    assert.match(docker, /USER nextjs/);
    assert.doesNotMatch(docker.slice(docker.indexOf("AS runner")), /USER root/);
    assert.match(docker, /\.next\/standalone/);
    assert.match(docker, /node_modules\/sharp/);
    const entry = fs.readFileSync("deployment/docker/docker-entrypoint.sh", "utf8");
    assert.match(entry, /migrate deploy/);
    assert.match(entry, /cấm migrate reset/);
    assert.doesNotMatch(entry, /prisma migrate reset|prisma db push/);
});

test("compose VPS 4 GB không publish Postgres, không build, restart always và giới hạn nhớ", () => {
    const compose = fs.readFileSync("deploy/docker-compose.yml", "utf8");
    assert.doesNotMatch(compose, /\n\s*build:/);
    assert.equal((compose.match(/restart: always/g) || []).length, 4);
    const db = compose.slice(compose.indexOf("\n  db:"), compose.indexOf("\n  app:"));
    assert.doesNotMatch(db, /^\s*ports:/m);
    assert.match(db, /mem_limit: 640m/);
    assert.match(compose, /mem_limit: 896m/);
    assert.match(compose, /mem_limit: 96m/);
    assert.match(compose, /mem_limit: 256m/);
    assert.match(compose, /internal: true/);
    assert.match(compose, /80:80/);
    assert.match(compose, /443:443/);
    const root = fs.readFileSync("docker-compose.yml", "utf8");
    assert.match(root, /deploy\/docker-compose\.yml/);
    const caddy = fs.readFileSync("deploy/Caddyfile", "utf8");
    assert.match(caddy, /quanlihocau\.com/);
    assert.match(caddy, /www\.quanlihocau\.com/);
    assert.match(caddy, /no-cache, no-store, must-revalidate/);
    assert.match(caddy, /sw\.js/);
    assert.match(caddy, /index\.html/);
    assert.match(caddy, /max-age=31536000, immutable/);
    assert.match(caddy, /X-Forwarded-For \{remote_host\}/);
});

test("backup, harden, migrate Neon và workflow chỉ bấm tay", () => {
    const backup = fs.readFileSync("deploy/scripts/backup.sh", "utf8");
    assert.match(backup, /S3_BUCKET/);
    assert.match(backup, /daily-\$\{STAMP\}\.dump\.gz/);
    assert.doesNotMatch(backup, /AKIA[0-9A-Z]{16}/);
    const harden = fs.readFileSync("deploy/scripts/harden.sh", "utf8");
    assert.match(harden, /swapfile/);
    assert.match(harden, /useradd/);
    assert.match(harden, /Accepted publickey for deploy/);
    assert.match(harden, /PasswordAuthentication no/);
    assert.match(harden, /PermitRootLogin no/);
    assert.match(harden, /ufw allow 80\/tcp/);
    assert.match(harden, /SSH_PORT="\$\{2:-24700\}"/);
    const allowSsh = harden.indexOf('ufw allow "${SSH_PORT}/tcp"');
    const enableUfw = harden.indexOf("ufw --force enable");
    assert.ok(allowSsh !== -1 && enableUfw !== -1 && allowSsh < enableUfw);
    assert.match(harden, /OneDash/);
    assert.doesNotMatch(harden, /ufw reset/);
    assert.match(harden, /fail2ban/);
    assert.match(harden, /unattended-upgrades/);
    assert.match(harden, /max-size/);
    assert.match(harden, /logrotate/);
    const migrate = fs.readFileSync("deploy/scripts/migrate-from-neon.sh", "utf8");
    assert.match(migrate, /pg_dump/);
    assert.match(migrate, /pg_restore/);
    assert.match(migrate, /count\(\*\)/);
    assert.doesNotMatch(migrate, /--clean|migrate reset|DROP DATABASE/);
    const restore = fs.readFileSync("deploy/scripts/restore-test.sh", "utf8");
    assert.match(restore, /quanlihocau_restore_test/);
    assert.match(restore, /DROP DATABASE IF EXISTS quanlihocau_restore_test/);
    const workflow = fs.readFileSync(".github/workflows/deploy.yml", "utf8");
    const header = workflow.split(/^jobs:/m)[0].replace(/#[^\n]*/g, "");
    assert.match(header, /workflow_dispatch/);
    assert.doesNotMatch(header, /^\s*push:/m);
    assert.doesNotMatch(header, /^\s*pull_request:/m);
    assert.doesNotMatch(header, /^\s*schedule:/m);
    assert.match(workflow, /inputs\.action == 'rollback'/);
    assert.match(fs.readFileSync("deploy/scripts/up.sh", "utf8"), /--no-build/);
    assert.match(fs.readFileSync("deploy/README.md", "utf8"), /2 vCPU/);
    assert.match(fs.readFileSync("docs/CHECKLIST_SAU_DEPLOY.md", "utf8"), /NEXTAUTH_URL/);
    assert.match(fs.readFileSync("deploy/docs/CAT_DNS.md", "utf8"), /MX/);
});
